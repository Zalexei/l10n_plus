import '../config.dart';
import '../model/localization_model.dart';

/// Emits the Flutter glue: a `BuildContext` extension and a controller factory.
///
/// Kept in a separate file so that a pure Dart consumer of the same
/// translations never sees a Flutter import.
final class FlutterEmitter {
  /// Creates an emitter.
  FlutterEmitter(this.model, this.config);

  /// The model to emit glue for.
  final LocalizationModel model;

  /// Generation options, for the context getter name.
  final L10nPlusConfig config;

  /// Renders the whole file.
  String emit() {
    final className = model.className;
    final localeEnum = model.localeEnumName;
    final controller = '${className}Controller';
    final getter = config.flutter.contextExtension;

    return '''
// GENERATED BY l10n_plus. DO NOT MODIFY BY HAND.
// Regenerate with: dart run l10n_plus_generator generate

// ignore_for_file: type=lint

import 'package:flutter/widgets.dart';
import 'package:l10n_plus_flutter/l10n_plus_flutter.dart';

import '${config.outputFileName}';

/// The locale controller type for [$className].
typedef $controller = L10nController<$localeEnum, $className>;

/// Creates the controller that drives locale switching.
///
/// Pass [locale] to pin a locale; omit it to follow the operating system.
///
/// [systemLocales] defaults to the platform's preferred locales, read once
/// here. Flutter reports `didChangeLocales` only when the locale *changes*,
/// so without this the first frame would always render the fallback locale.
/// Pass `const []` to opt out and start on the fallback regardless of the
/// device.
///
/// Reading them binds the Flutter engine, so this must be called from `main`
/// or later — which is where a controller is built anyway.
$controller create${className}Controller({
  $localeEnum? locale,
  List<Locale>? systemLocales,
}) {
  final resolvedSystemLocales =
      systemLocales ??
      WidgetsFlutterBinding.ensureInitialized().platformDispatcher.locales;
  return $controller(
    supportedLocales: $className.supportedLocales,
    fallbackLocale: $className.fallbackLocale,
    translationsOf: (locale) => locale.translations,
    initialLocale: locale,
    systemLocales: [
      for (final locale in resolvedSystemLocales) locale.toL10nLocale(),
    ],
  );
}

/// Locale list for `MaterialApp.supportedLocales`.
const List<Locale> ${_lowerFirst(className)}SupportedLocales = <Locale>[
${model.locales.map((locale) => '  ${_flutterLocaleLiteral(locale)},').join('\n')}
];

/// Reads translations from the nearest [L10nScope].
extension ${className}Context on BuildContext {
  /// Translations of the active locale.
  $className get $getter => L10nScope.of<$localeEnum, $className>(this);

  /// The controller of the nearest [L10nScope].
  $controller get ${getter}Controller =>
      L10nScope.controllerOf<$localeEnum, $className>(this);
}

/// Flutter interop for [$localeEnum].
extension ${localeEnum}Flutter on $localeEnum {
  /// This locale as a Flutter [Locale].
  Locale get flutterLocale => l10nLocale.toFlutterLocale();
}
''';
  }

  static String _flutterLocaleLiteral(LocaleModel locale) {
    final language = locale.locale.language;
    final script = locale.locale.script;
    final country = locale.locale.country;
    if (script == null && country == null) return "Locale('$language')";
    if (script == null) return "Locale('$language', '$country')";
    return 'Locale.fromSubtags('
        "languageCode: '$language', "
        "scriptCode: '$script'"
        "${country == null ? '' : ", countryCode: '$country'"})";
  }

  static String _lowerFirst(String value) =>
      value[0].toLowerCase() + value.substring(1);
}
